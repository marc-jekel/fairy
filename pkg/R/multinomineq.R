# Text of the analysis script that ships inside the multinomineq archive (the same text as in the Shiny app).
# The numbers of samples, the burn-in, the prior and the seed are set afterwards (see fairy_multinomineq_script()).
mn_script_base <- function() {
  paste(c(
    '#### Analysis with the multinomineq package ####',
    '# Put this script in one folder with the files of this download:',
    '#   A_<model>.csv, b_<model>.csv   H-representation',
    '#   map_<model>.csv                only with equal probabilities',
    '#   V_<model>.csv                  V-representation (not used; see the commented lines in analyse())',
    '#   data_choices*.csv              your data (see below)',
    '# Then run the whole script. It analyses EVERY model in the',
    '# folder and writes results.csv (Bayes factors),',
    '# posterior.csv (estimates of the probabilities) and',
    '# results.html (the main results as a web page).',
    '# Package: https://www.dwheck.de/software/multinomineq/',
    '#',
    '# Equalities: multinomineq needs a model with positive volume.',
    '# Exact equalities between two probabilities (p1 = p2) are',
    '# handled: the files have fewer columns, and map_<model>.csv',
    '# says which probabilities are equal. Other exact equalities',
    '# (p1 = 0.3, p1 = p2 + p3) give volume zero: set them to',
    '# "Approximate" in the app before you download.',
    '#',
    '# Your data: open the data file(s) next to this script and',
    '# replace the example numbers by your own (or enter them in the',
    '# app first: Data button next to the download).',
    '#   data_choices.csv: for the models with the same probabilities',
    '#   (if they differ in number: data_choices_<k>_probabilities.csv)',
    '#   data_model_<name>.csv: only for that model (unpacked items',
    '#   models: their probabilities mean something of their own)',
    '#   The script takes, for each model, the first file that exists.',
    '#   One row per probability, in the order of the columns of A / V.',
    '#   n          number of observations for this probability',
    '#   frequency  how often the outcome the probability stands for',
    '#              was observed, out of n (e.g. how often the option',
    '#              with choice probability p1 was chosen)',
    '',
    '#### Settings ####',
    'final <- FALSE   # TRUE: more samples for the final numbers',
    '                 # (takes longer, smaller standard error)',
    'plots <- FALSE   # TRUE: one plot of the posterior per model',
    '# Advanced: the prior. Beta(1, 1) = uniform on every probability',
    '# (default of multinomineq).',
    'prior <- c(1, 1)',
    '# (for even more samples set M_post and M_bf to larger numbers)',
    'M_post <- if (final) 20000 else 5000     # posterior samples',
    'M_bf <- if (final) 100000 else 10000     # Bayes factor samples',
    '# Advanced: draws discarded at the start (burn-in); these are the',
    '# defaults of multinomineq. The seed makes a run repeatable.',
    'burnin_post <- 10   # posterior',
    'burnin_bf <- 5      # Bayes factors (per step)',
    '',
    '#### Packages (installed if missing) ####',
    'for (p in c("multinomineq", "rcdd", "coda")) {',
    '  if (!requireNamespace(p, quietly = TRUE)) install.packages(p)',
    '}',
    'library("rcdd")',
    'library("multinomineq")',
    'library("coda")',
    'seed <- 1234   # makes a run repeatable; every model gets its own random numbers',
    '',
    '# In RStudio: work in the folder of this script',
    'try({',
    '  if (requireNamespace("rstudioapi", quietly = TRUE) &&',
    '      rstudioapi::isAvailable()) {',
    '    here <- dirname(rstudioapi::getSourceEditorContext()$path)',
    '    if (nzchar(here) && here != ".") setwd(here)',
    '  }',
    '}, silent = TRUE)',
    '',
    '#### Helper functions ####',
    '# numbers or fractions such as 1/2',
    'read_q <- function(x) {',
    '  if (is.numeric(unlist(x))) {',
    '    matrix(unlist(x), ncol = ncol(x))',
    '  } else {',
    '    matrix(q2d(unlist(x)), ncol = ncol(x))',
    '  }',
    '}',
    '# one row: all Bayes factors of bf_binom with error and interval',
    'bf_row <- function(model, rep, bf, note = "") {',
    '  out <- data.frame(model = model, representation = rep)',
    '  for (r in c("bf_0u", "bf_u0", "bf_00\'")) {',
    '    nm <- sub("\'", "", r)',
    '    out[[nm]] <- bf[r, "bf"]',
    '    out[[paste0(nm, "_se")]] <- bf[r, "se"]',
    '    out[[paste0(nm, "_ci5")]] <- bf[r, "ci.5%"]',
    '    out[[paste0(nm, "_ci95")]] <- bf[r, "ci.95%"]',
    '  }',
    '  if (!nzchar(note) && any(c(out$bf_0u, out$bf_00) == 0,',
    '                           na.rm = TRUE))',
    '    note <- paste("The estimate is 0: the data speak strongly",',
    '                  "against the model (no sample fell inside it), so",',
    '                  "the true value is very small but not 0. More",',
    '                  "samples may give a number.")',
    '  if (!nzchar(note) && is.finite(out$bf_0u) && !is.finite(out$bf_00))',
    '    note <- paste("multinomineq gives no Bayes factor against the",',
    '                  "complement (everything the model forbids) for a",',
    '                  "model with equalities. The Bayes factor against",',
    '                  "the unconstrained model is not affected.")',
    '  out$note <- note',
    '  out',
    '}',
    'empty_bf <- matrix(NA_real_, 3, 4, dimnames = list(',
    '  c("bf_0u", "bf_u0", "bf_00\'"), c("bf", "se", "ci.5%", "ci.95%")))',
    '',
    '# plain explanations for models that cannot be computed',
    'no_result <- paste("No result: the model has volume, but not even",',
    '  "the stepwise method found a point inside it (very thin?).",',
    '  "Try final <- TRUE; if it still fails, check the files.")',
    'friendly <- function(msg) {',
    '  if (grepl("Truncation|min<max|boundar", msg))',
    '    return(paste("The sampler could not start. The model probably",',
    '      "has volume zero or is extremely thin; check the equalities",',
    '      "in the app and download the files again.",',
    '      "Technical message:", msg))',
    '  if (grepl("data file|needs one row|cannot be larger", msg))',
    '    return(msg)',
    '  paste("Unexpected problem:", msg, "- check that all files of",',
    '        "the download are in this folder.")',
    '}',
    '# labels like p_{1}^{(2)} as plotmath for the plot titles',
    'to_plotmath <- function(x) {',
    '  gsub("_[{]([^}]*)[}]", "[\\\\1]", x)   # ^{...} is plotmath already',
    '}',
    'plot_title <- function(label, what) {',
    '  e <- tryCatch(parse(text = to_plotmath(label))[[1]],',
    '                error = function(err) label)',
    '  bquote(.(e) ~ .(what))',
    '}',
    '# diagnostics of the posterior sample: ESS, Geweke z and an svg plot',
    'n_svg <- 0',
    'diag_rows <- function(model, rep, post, labels) {',
    '  m <- as.matrix(post); k <- ncol(m)',
    '  if (length(labels) != k) labels <- colnames(m)',
    '  ess <- tryCatch(as.numeric(coda::effectiveSize(post)),',
    '                  error = function(e) rep(NA_real_, k))',
    '  gz <- tryCatch(as.numeric(coda::geweke.diag(post)$z),',
    '                 error = function(e) rep(NA_real_, k))',
    '  f <- tempfile(fileext = ".svg")',
    '  svg_txt <- tryCatch({',
    '    svg(f, width = 8, height = 1.5 * k + 0.4)',
    '    op <- par(mfrow = c(k, 2), mar = c(2.2, 3, 1.4, 1),',
    '              mgp = c(1.6, 0.5, 0))',
    '    for (i in seq_len(k)) {',
    '      keep <- unique(round(seq(1, nrow(m), length.out = 1000)))',
    '      plot(keep, m[keep, i], type = "l", col = "#593196",',
    '           xlab = "", ylab = "",',
    '           main = plot_title(labels[i], "trace"))',
    '      plot(density(m[, i]), xlab = "", ylab = "", lwd = 2,',
    '           col = "#593196",',
    '           main = plot_title(labels[i], "density"))',
    '    }',
    '    par(op); dev.off()',
    '    x <- paste(readLines(f, warn = FALSE), collapse = " ")',
    '    n_svg <<- n_svg + 1',
    '    x <- sub("^<[?]xml[^>]*>", "", x)',
    '    # the curves follow the accent colour of the page (purple by day, blue at night)',
    '    x <- gsub(\'stroke="rgb[(]34[.]9[0-9]*%, *19[.]2[0-9]*%, *58[.]8[0-9]*%[)]"\',',
    '              \'stroke="#593196" style="stroke:var(--prim,#593196)"\', x)',
    '    x <- gsub("glyph-", paste0("g", n_svg, "glyph-"), x, fixed = TRUE)',
    '    gsub("clip", paste0("c", n_svg, "clip"), x, fixed = TRUE)',
    '  }, error = function(e) NULL)',
    '  unlink(f)',
    '  list(model = model, rep = rep, labels = labels, ess = ess,',
    '       n_draws = nrow(m), geweke = gz, svg = svg_txt,',
    '       draws = m[unique(round(seq(1, nrow(m), length.out = min(nrow(m), 2000)))), , drop = FALSE])',
    '}',
    '# posterior of every probability: mean, SD, 95% interval',
    'post_rows <- function(model, rep, post, labels) {',
    '  m <- as.matrix(post)',
    '  if (length(labels) != ncol(m)) labels <- colnames(m)',
    '  data.frame(model = model, representation = rep,',
    '    probability = labels, mean = colMeans(m),',
    '    sd = apply(m, 2, sd),',
    '    ci2.5 = apply(m, 2, quantile, 0.025),',
    '    ci97.5 = apply(m, 2, quantile, 0.975), row.names = NULL)',
    '}',
    '',
    '# long model names are shortened where space is tight',
    'short_name <- function(x, n = 28) {',
    '  ifelse(nchar(x) > n, paste0(substr(x, 1, n - 3), "..."), x)',
    '}',
    '',
    '# progress messages (the app shows them while the analysis runs)',
    'cur <- new.env()',
    'status <- function(txt) {',
    '  cat(sprintf("[%d/%d] %s: %s\\n", cur$i, cur$n,',
    '              short_name(cur$model, 40), txt))',
    '  flush.console()',
    '}',
    '',
    '#### Analysis of one model ####',
    'analyse <- function(model_name) {',
    '  file_A <- paste0("A_", model_name, ".csv")',
    '  file_V <- paste0("V_", model_name, ".csv")',
    '  A <- b <- V <- NULL',
    '  if (file.exists(file_A)) {',
    '    A_raw <- read.csv(file_A, check.names = FALSE,',
    '                      stringsAsFactors = FALSE)',
    '    A <- read_q(A_raw); colnames(A) <- colnames(A_raw)',
    '    b <- unlist(read.csv(paste0("b_", model_name, ".csv"),',
    '                  header = FALSE, stringsAsFactors = FALSE))',
    '    if (!is.numeric(b)) b <- q2d(b)',
    '  }',
    '  # Analysis from the V-representation (vertices) is possible but switched off: the app always analyses the',
    '  # H-representation (A and b). To use it, remove the # here and in the line with one("V", V = V) below, and',
    '  # put the file V_<model>.csv (one vertex per row) next to the A_ and b_ files.',
    '  # if (file.exists(file_V)) {',
    '  #   V_raw <- read.csv(file_V, check.names = FALSE,',
    '  #                     stringsAsFactors = FALSE)',
    '  #   V <- read_q(V_raw); colnames(V) <- colnames(V_raw)',
    '  # }',
    '  # does the model have volume? (the app checked the files)',
    '  info <- if (file.exists("model_info.csv")) {',
    '    read.csv("model_info.csv", stringsAsFactors = FALSE)',
    '  } else NULL',
    '  zero <- !is.null(info) && any(info$model == model_name &',
    '                                 info$volume == "zero")',
    '  if (zero) {',
    '    why <- info$reason[info$model == model_name][1]',
    '    return(list(bf = bf_row(model_name, if (!is.null(A)) "H" else "V",',
    '      empty_bf, paste0("This model has volume zero: ", why, ".",',
    '      " multinomineq needs a model with volume. In the app set",',
    '      " such equalities to Approximate and download again.")),',
    '      posterior = NULL, diag = NULL))',
    '  }',
    '  # equal probabilities: map says which parameter each belongs to',
    '  file_map <- paste0("map_", model_name, ".csv")',
    '  n_free <- if (!is.null(A)) ncol(A) else ncol(V)',
    '  map <- if (file.exists(file_map)) {',
    '    read.csv(file_map, header = FALSE)[[1]]',
    '  } else seq_len(n_free)',
    '  n_p <- length(map)',
    '',
    '  # your data for this number of probabilities',
    '  data_file <- c(paste0("data_model_", model_name, ".csv"),',
    '                 paste0("data_choices_", n_p, "_probabilities.csv"),',
    '                 "data_choices.csv")',
    '  data_file <- data_file[file.exists(data_file)][1]',
    '  if (is.na(data_file))',
    '    stop("No data file found for model ", model_name, ": expected",',
    '         " data_choices.csv or data_model_", model_name,',
    '         ".csv next to this script.")',
    '  dat <- read.csv(data_file, stringsAsFactors = FALSE)',
    '  n <- dat$n',
    '  choices <- dat$frequency',
    '  if (length(choices) != n_p)',
    '    stop(data_file, " needs one row for each of the ", n_p,',
    '         " probabilities of this model.")',
    '  if (any(choices > n))',
    '    stop("In ", data_file, ": frequency cannot be larger than n.")',
    '',
    '  # posterior: equal probabilities share one parameter, so add up',
    '  # their counts (sampling_binom with map needs a start value)',
    '  k_use <- as.vector(tapply(choices, map, sum))',
    '  n_use <- as.vector(tapply(n, map, sum))',
    '  rows <- list(); post <- list(); dg <- list(); note <- ""',
    '  one <- function(rep, ...) {',
    '    status(paste0("drawing the posterior (", rep, ")"))',
    '    p <- tryCatch(sampling_binom(k = k_use, n = n_use, ...,',
    '      prior = prior, M = M_post, burnin = burnin_post,',
    '      progress = FALSE),',
    '      error = function(e) NULL)',
    '    if (is.null(p)) {',
    '      note <<- paste("No posterior could be drawn: the sampler",',
    '        "could not start (the data are far from the model, or",',
    '        "the model has no volume).")',
    '    } else {',
    '      labs <- colnames(if (rep == "V") V else A)',
    '      post[[rep]] <<- post_rows(model_name, rep, p, labs)',
    '      dg[[rep]] <<- diag_rows(model_name, rep, p, labs)',
    '      if (plots) plot(p)',
    '    }',
    '    status(paste0("estimating the Bayes factors (", rep, ")"))',
    '    # with map the equalities belong to the model; the',
    '    # unconstrained model has all probabilities free',
    '    bf <- bf_binom(k = choices, n = n, ..., map = map,',
    '                   prior = prior, M = M_bf, burnin = burnin_bf,',
    '                   progress = FALSE)',
    '    # very small models: no sample falls inside. Then use the',
    '    # stepwise method of the package (one constraint at a time)',
    '    first <- bf["bf_0u", "bf"]',
    '    # (only for a very thin model; with data far from the model the',
    '    # stepwise method can run for a very long time)',
    '    if (!is.finite(first)) {',
    '      status("very small model: stepwise estimate")',
    '      bf2 <- tryCatch(bf_binom(k = choices, n = n, ..., map = map,',
    '        prior = prior, M = M_bf, cmin = 100, burnin = burnin_bf,',
    '        progress = FALSE),',
    '        error = function(e) NULL)',
    '      if (!is.null(bf2) && is.finite(bf2["bf_0u", "bf"])) {',
    '        bf <- bf2',
    '        note <<- paste("The model has a very small volume:",',
    '                       "computed stepwise (less precise, see se).",',
    '                       "For a more precise value use more samples (in the",',
    '                       "app: Run window, Number of samples; in the",',
    '                       "script: M_bf).")',
    '      }',
    '    }',
    '    rows[[rep]] <<- bf_row(model_name, rep, bf,',
    '      if (is.finite(bf["bf_0u", "bf"])) note else no_result)',
    '  }',
    '  # if (!is.null(V)) one("V", V = V)   # analysis from the vertices, see above',
    '  if (!is.null(A)) one("H", A = A, b = b)',
    '  list(bf = do.call(rbind, rows), posterior = do.call(rbind, post),',
    '       diag = unname(dg))',
    '}',
    '',
    '#### Run all models ####',
    '# (to analyse from V_<model>.csv files as well, use [AbV] instead of [Ab] in both places)',
    'models <- unique(sub("^[Ab]_(.*)\\\\.csv$", "\\\\1",',
    '                     list.files(pattern = "^[Ab]_.*\\\\.csv$")))',
    'cat("Working directory:", getwd(), "\\n")',
    'if (length(models) == 0)',
    '  stop("No A_*.csv files found in ", getwd(), ". Put this",',
    '       " script in the folder with the downloaded files (RStudio:",',
    '       " Session > Set Working Directory > To Source File Location).")',
    '# the order of the Input page (model_order.txt of the download), else',
    '# the alphabetical order of the files',
    'if (file.exists("model_order.txt")) {',
    '  ord <- readLines("model_order.txt")',
    '  models <- c(intersect(ord, models), setdiff(models, ord))',
    '}',
    'cat("Models found:", paste(models, collapse = ", "), "\\n")',
    '# Optional arguments (the app uses them to run every model in its own',
    '# process; without arguments the script analyses all models):',
    '#   only=<model>   analyse this model and save res_<model>.rds',
    '#   report         build the tables and results.html from the res_*.rds',
    'args <- commandArgs(TRUE)',
    'only <- sub("^only=", "", args[grepl("^only=", args)])',
    'run_one <- function(i) {',
    '  m <- models[i]',
    '  set.seed(seed + i)',
    '  cur$i <- i; cur$n <- length(models); cur$model <- m',
    '  status("starting")',
    '  res <- tryCatch(analyse(m), error = function(e) {',
    '    list(bf = bf_row(m, NA, empty_bf, friendly(conditionMessage(e))),',
    '         posterior = NULL, diag = NULL)',
    '  })',
    '  cat("\\n==== Model", m, "====\\n")',
    '  print(res$bf[, c("representation", "bf_0u", "bf_0u_se",',
    '                   "bf_u0", "bf_00", "note")], row.names = FALSE)',
    '  if (!is.null(res$posterior))',
    '    print(res$posterior[, -1], row.names = FALSE)',
    '  res',
    '}',
    'skipped <- character(0)',
    'if (length(only) == 1) {',
    '  saveRDS(run_one(match(only, models)), paste0("res_", only, ".rds"))',
    '  quit(save = "no")',
    '}',
    'if ("report" %in% args) {',
    '  have <- models[file.exists(paste0("res_", models, ".rds"))]',
    '  skipped <- setdiff(models, have)',
    '  if (file.exists("skipped.txt")) skipped <- union(skipped, readLines("skipped.txt"))',
    '  runs <- lapply(have, function(m) readRDS(paste0("res_", m, ".rds")))',
    '} else {',
    '  # every model is shown as soon as it is done',
    '  runs <- lapply(seq_along(models), run_one)',
    '}',
    'results <- do.call(rbind, lapply(runs, `[[`, "bf"))',
    'posterior <- do.call(rbind, lapply(runs, `[[`, "posterior"))',
    'diags <- unlist(lapply(runs, `[[`, "diag"), recursive = FALSE)',
    'cat("\\n==== All models ====\\n")',
    'print(results[, c("model", "representation", "bf_0u",',
    '                  "bf_0u_se", "bf_00", "note")], row.names = FALSE)',
    'write.csv(results, "results.csv", row.names = FALSE)',
    'if (!is.null(posterior))',
    '  write.csv(posterior, "posterior.csv", row.names = FALSE)',
    '#### Overview as a web page (results.html) ####',
    'esc <- function(x) {',
    '  x <- gsub("&", "&amp;", x, fixed = TRUE)',
    '  x <- gsub("<", "&lt;", x, fixed = TRUE)',
    '  gsub(">", "&gt;", x, fixed = TRUE)',
    '}',
    '# numbers: scientific for very small ones (below 0.01)',
    'num <- function(x, d = 3) {',
    '  small <- is.finite(x) & x != 0 & abs(x) < 0.01',
    '  txt <- trimws(formatC(x, digits = d, format = "g"))',
    '  txt[small] <- sprintf(paste0("%.", d - 1, "e"), x[small])',
    '  ifelse(is.finite(x), txt, "-")',
    '}',
    '# one table; cls = colour class per cell, raw = columns with html',
    'html_table <- function(df, cls = NULL, raw = character()) {',
    '  df[] <- lapply(df, as.character)',
    '  head <- paste0("<th>", esc(names(df)), "</th>", collapse = "")',
    '  body <- vapply(seq_len(nrow(df)), function(i) {',
    '    cells <- vapply(seq_along(df), function(j) {',
    '      cl <- if (is.null(cls)) "" else cls[i, j]',
    '      txt <- if (names(df)[j] %in% raw) df[i, j] else esc(df[i, j])',
    '      if (nzchar(cl)) paste0("<td class=c><span class=", cl, ">",',
    '                             txt, "</span></td>")',
    '      else paste0("<td>", txt, "</td>")',
    '    }, "")',
    '    paste0("<tr>", paste(cells, collapse = ""), "</tr>")',
    '  }, "")',
    '  c("<div class=tw><table>", paste0("<tr>", head, "</tr>"), body, "</table></div>")',
    '}',
    '# labels like p_{1}^{(2)} as html: stacked index and exponent',
    'lab_html <- function(x) {',
    '  x <- esc(x)',
    '  x <- gsub("_[{]([^}]*)[}][\\\\^][{]([^}]*)[}]",',
    '            "<span class=ss><sup>\\\\2</sup><sub>\\\\1</sub></span>", x)',
    '  x <- gsub("_[{]([^}]*)[}]", "<sub>\\\\1</sub>", x)',
    '  gsub("[\\\\^][{]([^}]*)[}]", "<sup>\\\\1</sup>", x)',
    '}',
    '# an estimate of exactly 0 means: no sample fell inside the model',
    'with_se <- function(bf, se) {',
    '  ifelse(is.finite(bf),',
    '         ifelse(bf == 0, paste0("< ", num(se, 2)),',
    '                paste0(num(bf), " (se ", num(se, 2), ")")), "-")',
    '}',
    '# colour of a Bayes factor: green for the model, red against it;',
    '# the categories of Jeffreys (1961) as given by Lee & Wagenmakers',
    '# (2013): 1-3 anecdotal, 3-10 moderate, 10-30 strong,',
    '# 30-100 very strong, above 100 extreme (and the inverse)',
    'bf_class <- function(x) {',
    '  cl <- as.character(cut(x, c(-Inf, 1/100, 1/30, 1/10, 1/3, 1, 3,',
    '                              10, 30, 100, Inf),',
    '                         labels = paste0("b", 1:10)))',
    '  ifelse(is.finite(x), cl, "")',
    '}',
    '# the column of the representation is only shown if V was analysed as well (the app itself always uses H)',
    'show_rep <- any(results$representation != "H", na.rm = TRUE)',
    'drop_rep_cols <- function(d, i) if (show_rep) d else d[, -i, drop = FALSE]',
    'key <- data.frame(',
    '  Model = results$model,',
    '  Representation = results$representation,',
    '  "Bayes factor, model vs. unconstrained" =',
    '    with_se(results$bf_0u, results$bf_0u_se),',
    '  "Bayes factor, model vs. complement" =',
    '    with_se(results$bf_00, results$bf_00_se),',
    '  Note = ifelse(nzchar(results$note), "see below", ""),',
