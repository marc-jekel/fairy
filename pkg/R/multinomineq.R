#' Text of the multinomineq analysis script
#'
#' The R script that is shipped inside the multinomineq archive of
#' [fairy_write_multinomineq()] (the same text as in the Shiny app). It reads the
#' files next to it (`A_<model>.csv`, `b_<model>.csv`, optional `map_<model>.csv`
#' and the data files), runs the analysis of every model with the `multinomineq`
#' package (Heck & Davis-Stober, 2019) and writes `results.csv` (Bayes factors),
#' `posterior.csv` (estimates of the probabilities) and `results.html`.
#'
#' @param posterior_samples Number of samples for the posterior. Default `5000`.
#' @param bf_samples Number of samples for the Bayes factors. Default `10000`.
#' @param burnin_post,burnin_bf Burn-in of the posterior and of the Bayes factors
#'   (the defaults of multinomineq: `10` and `5`).
#' @param prior The two numbers `a` and `b` of the Beta prior of every probability.
#'   Default `c(1, 1)`, the uniform prior.
#' @param seed Seed that makes a run repeatable. Default `1234`.
#'
#' @return One character string with the script.
#' @examples
#' cat(substr(fairy_multinomineq_script(bf_samples = 50000, seed = 1), 1, 300))
#' @export
fairy_multinomineq_script <- function(posterior_samples = 5000, bf_samples = 10000, burnin_post = 10,
                                      burnin_bf = 5, prior = c(1, 1), seed = 1234) {
  if (length(prior) != 2 || any(!is.finite(prior)) || any(prior <= 0)) stop("'prior' must be two positive numbers.", call. = FALSE)
  if (posterior_samples < 100 || bf_samples < 100 || posterior_samples != round(posterior_samples) || bf_samples != round(bf_samples))
    stop("The numbers of samples must be whole numbers, 100 or more.", call. = FALSE)
  if (burnin_post < 0 || burnin_bf < 0 || burnin_post != round(burnin_post) || burnin_bf != round(burnin_bf))
    stop("Burn-in must be a whole number, 0 or more.", call. = FALSE)
  fmt <- function(x) format(x, scientific = FALSE, trim = TRUE)
  ln <- strsplit(mn_script_base(), "\n", fixed = TRUE)[[1]]
  # "final" only says that more than the default number of samples is used (the notes of the results refer to it)
  if (bf_samples > 10000 || posterior_samples > 5000) ln <- sub("^final <- FALSE.*", "final <- TRUE", ln)
  ln <- sub("^M_post <- .*", paste0("M_post <- ", fmt(posterior_samples)), ln)
  ln <- sub("^M_bf <- .*", paste0("M_bf <- ", fmt(bf_samples)), ln)
  ln <- sub("^burnin_post <- [0-9.]+", paste0("burnin_post <- ", fmt(burnin_post)), ln)
  ln <- sub("^burnin_bf <- [0-9.]+", paste0("burnin_bf <- ", fmt(burnin_bf)), ln)
  ln <- sub("^prior <- c\\(1, 1\\)", paste0("prior <- c(", fmt(prior[1]), ", ", fmt(prior[2]), ")"), ln)
  ln <- sub("^seed <- 1234", paste0("seed <- ", fmt(round(seed))), ln)
  paste(ln, collapse = "\n")
}

# Data files of the analysis: one row per probability (name, n, frequency), written next to the script. A model takes the first file
# that exists: data_model_<name>.csv, data_choices_<k>_probabilities.csv, data_choices.csv. `info` is a list (named by model) of
# list(labels = probability names in the order of the columns, stem = file name part of the model).
# data: NULL (example numbers: decreasing frequencies, equal ones can stop the sampler), one data frame (probability, n, frequency)
# for the models with that many probabilities, or a list of such data frames: named by model (own file) or unnamed (matched by size).
mn_write_data <- function(info, data = NULL) {
  as_df <- function(d) {
    if (!is.data.frame(d)) stop("'data' must be a data frame (columns probability, n, frequency) or a list of them.", call. = FALSE)
    if (!all(c("n", "frequency") %in% names(d))) stop("A data frame in 'data' needs the columns n and frequency (and probability).", call. = FALSE)
    d
  }
  if (is.data.frame(data)) data <- list(data)
  if (!is.null(data)) data <- lapply(data, as_df)
  ks <- vapply(info, function(i) length(i$labels), integer(1))
  base_ks <- sort(unique(ks))
  own <- if (!is.null(data) && !is.null(names(data))) intersect(names(data), names(info)) else character(0)
  one_file <- length(base_ks) == 1
  fill <- function(d, labels) {
    k <- length(labels)
    ex <- round(25 * seq(0.8, 0.2, length.out = k))
    if (is.null(d)) return(data.frame(probability = labels, n = rep(25L, k), frequency = as.integer(ex), stringsAsFactors = FALSE))
    if (nrow(d) != k) stop("The data have ", nrow(d), " rows but the model has ", k, " probabilities.", call. = FALSE)
    # the numbers belong to the probability name: "p1" and "p_{1}" are the same probability
    norm <- function(x) gsub("[_{} ]", "", as.character(x))
    idx <- if ("probability" %in% names(d) && all(norm(labels) %in% norm(d$probability))) match(norm(labels), norm(d$probability)) else seq_len(k)
    data.frame(probability = labels, n = as.integer(d$n[idx]), frequency = as.integer(d$frequency[idx]), stringsAsFactors = FALSE)
  }
  by_size <- function(k) {
    if (is.null(data)) return(NULL)
    unnamed <- data[is.null(names(data)) | names(data) == ""]
    if (is.null(names(data))) unnamed <- data
    for (d in unnamed) if (nrow(d) == k) return(d)
    NULL
  }
  out <- character(0)
  for (nm in own) {
    f <- paste0("data_model_", info[[nm]]$stem, ".csv")
    utils::write.csv(fill(data[[nm]], info[[nm]]$labels), f, row.names = FALSE, quote = FALSE); out <- c(out, f)
  }
  for (k in base_ks) {
    members <- names(info)[ks == k]
    if (all(members %in% own)) next
    first <- info[[members[!(members %in% own)][1]]]
    f <- if (one_file) "data_choices.csv" else paste0("data_choices_", k, "_probabilities.csv")
    utils::write.csv(fill(by_size(k), first$labels), f, row.names = FALSE, quote = FALSE); out <- c(out, f)
  }
  out
}

#' Run the multinomineq analysis of a set of models
#'
#' Writes the same files as [fairy_write_multinomineq()] into a folder, runs the analysis script there and
#' returns the results: the Bayes factors of every model (against the unconstrained model and against its
#' complement) and the posterior estimates of the probabilities. Needs the packages `multinomineq` and `coda`.
#'
#' @inheritParams fairy_write_multinomineq
#' @param dir Folder for the files and the results. Default: a new temporary folder.
#' @return A list with `results` (data frame `results.csv`), `posterior` (data frame `posterior.csv`), `dir`, and
#'   `report` (path of `results.html`, or `NA`).
#' @examples
#' \dontrun{
#' r <- fairy_analyze_multinomineq(c(H1 = "p1 > p2 > p3", H2 = "p1 > p2"), n_p = 3,
#'   data = data.frame(probability = c("p1", "p2", "p3"), n = c(30, 30, 30), frequency = c(21, 12, 9)),
#'   settings = list(bf_samples = 20000, seed = 1))
#' r$results
#' }
#' @export
fairy_analyze_multinomineq <- function(models, data = NULL, n_p = NULL, settings = list(), dir = NULL, approx_tol = 0,
                                       reduce = TRUE, order = NULL) {
  for (p in c("multinomineq", "coda")) if (!requireNamespace(p, quietly = TRUE)) stop("Package '", p, "' is needed for the analysis.", call. = FALSE)
  if (is.null(dir)) dir <- tempfile("fairy_multinomineq_")
  dir.create(dir, showWarnings = FALSE, recursive = TRUE)
  dir <- normalizePath(dir)
  mn_write_files(models, n_p, dir, approx_tol, reduce, order, data, settings, analysis = TRUE)
  owd <- setwd(dir); on.exit(setwd(owd), add = TRUE)
  utils::capture.output(suppressMessages(source("analysis_multinomineq.R", local = new.env(), echo = FALSE)))
  rd <- function(f) if (file.exists(f)) utils::read.csv(f, check.names = FALSE) else NULL
  list(results = rd("results.csv"), posterior = rd("posterior.csv"), dir = dir,
       report = if (file.exists("results.html")) file.path(dir, "results.html") else NA_character_)
}
