test_that("H and V tables have the right shape", {
  h <- fairy_h("p1 > p2 > p3", n_p = 3)
  th <- fairy_h_table(h)
  expect_s3_class(th, "fairy_table")
  expect_equal(nrow(th), 4)
  expect_true(all(c("Constraint", "Type") %in% colnames(th)))
  tm <- fairy_h_table(h, style = "matrix", labels = c("A", "B", "C"))
  expect_equal(colnames(tm), c("A", "B", "C", "relation", "b"))
  tv <- fairy_v_table(h)
  expect_equal(dim(tv), c(4, 3))
  expect_equal(rownames(tv)[1], "V1")
  expect_true(all(unlist(fairy_v_table(h, words = TRUE)) %in% c("none", "all")))
  e <- fairy_h_table("p1 = p2; p2 > p3", n_p = 3, style = "matrix")
  expect_true("=" %in% e$relation)
})

test_that("fairy_table_write gives markdown, latex and csv", {
  v <- fairy_v_table("p1 > p2", n_p = 2)
  md <- fairy_table_write(v)
  expect_equal(length(md), nrow(v) + 2)
  expect_true(all(grepl("^\\|", md)))
  expect_true(any(grepl("begin\\{tabular\\}", fairy_table_write(v, format = "latex"))))
  f <- tempfile(fileext = ".csv"); fairy_table_write(v, file = f, format = "csv")
  expect_equal(length(readLines(f)), nrow(v) + 1)
})
