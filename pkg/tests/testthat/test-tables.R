test_that("H and V tables have the right shape", {
  h <- fairy_h("p1 > p2 > p3", n_p = 3)
  th <- fairy_h_table(h)
  expect_s3_class(th, "fairy_table")
  expect_equal(nrow(th), 4)
  expect_false(any(grepl("-", th$Constraint)))
  expect_true(all(c("p2 <= p1", "p3 <= p2") %in% th$Constraint))
  expect_true("- p1 + p2 <= 0" %in% fairy_h_table(h, style = "paper")$Constraint)
  expect_true(any(grepl("^1/10 <= p3$", fairy_h_table("p1 > p2 > p3; p3 > .1", n_p = 3)$Constraint)))
  expect_true("p2 = p3" %in% fairy_h_table("p1 < p2; p2 = p3", n_p = 3)$Constraint)
  expect_true(all(c("Constraint", "Type") %in% colnames(th)))
  tm <- fairy_h_table(h, style = "matrix", labels = c("A", "B", "C"))
  expect_equal(colnames(tm), c("A", "B", "C", "relation", "b"))
  tv <- fairy_v_table(h)
  expect_equal(dim(tv), c(4, 3))
  expect_equal(rownames(tv)[1], "V1")
  expect_true(all(unlist(fairy_v_table(h, words = TRUE)) %in% c("none", "all")))
  e <- fairy_h_table("p1 = p2; p2 > p3", n_p = 3, style = "matrix")
  expect_true("=" %in% e$relation)
})

test_that("fairy_table_write gives markdown, latex and csv", {
  v <- fairy_v_table("p1 > p2", n_p = 2)
  md <- fairy_table_write(v)
  expect_equal(length(md), nrow(v) + 2)
  expect_true(all(grepl("^\\|", md)))
  expect_true(any(grepl("begin\\{tabular\\}", fairy_table_write(v, format = "latex"))))
  f <- tempfile(fileext = ".csv"); fairy_table_write(v, file = f, format = "csv")
  expect_equal(length(readLines(f)), nrow(v) + 1)
})

test_that("H-description as LaTeX is readable and follows the trivial-bounds setting", {
  h <- fairy_h("p1 > p2 > p3", n_p = 3)
  all_rows <- fairy_h_latex(h)
  expect_true(all(c("p_{2} &\\leq p_{1} \\\\", "p_{3} &\\leq p_{2} \\\\") %in% all_rows))
  expect_equal(length(all_rows), 4)
  expect_equal(length(fairy_h_latex(h, trivial = "hide")), 2)
  expect_true(any(grepl("textcolor\\{gray\\}", fairy_h_latex(h, trivial = "gray"))))
  # items: the item number in parentheses becomes a proper superscript
  u <- fairy_unpack(h, items = c(2, 2, 2), lists = c("l1", "l2", "l3"), type = c(l1 = "average", l2 = "average", l3 = "average"), eps = c(0, 0, 0))
  expect_true(any(grepl("p_{2}^{(1)}", fairy_h_latex(u), fixed = TRUE)))
  tex <- fairy_write_latex(list(a = h, `b_c` = "p1 > p2"), n_p = 3)
  expect_true(any(grepl("begin\\{document\\}", tex)) && any(grepl("subsection\\*\\{b\\\\_c\\}", tex)))
  f <- tempfile(fileext = ".tex"); fairy_write_latex(list(a = h), file = f)
  expect_true(any(grepl("align\\*", readLines(f))))
})
